export const AVAILABLE_CATEGORY_ICONS: string[] = Object.keys(ICON_MAP);

export const CategoryIcon: React.FC<CategoryIconProps> = ({
  name,
  size = 20,
  color,
  className = '',
  walletName
}) => {
  // Kiểm tra nếu là Logo Ngân hàng hoặc Ví điện tử
  const brand = detectBankBrand(name, walletName);
  if (brand) {
    return <BankLogo brand={brand} size={Math.max(size + 8, 28)} className={className} />;
  }

  const IconComponent = ICON_MAP[name] || CircleDot;
  return <IconComponent size={size} color={color} className={className} />;
};

